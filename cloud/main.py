# The lobby features one guide. Manual override (tools/featured.json, baked into
# static/_lobby/featured.json at build) wins; otherwise the guide with the most
# GA4 views over the last 7 days, refreshed every 6 h; otherwise the default.
# GA access: grant the Cloud Run service account Viewer on GA4 property 563092930
# and enable the Google Analytics Data API in the GCP project. Until then this
# quietly falls back to the default.
GA4_PROPERTY = "563092930"
_LOBBY = STATIC / "_lobby"
_top_guide = {"slug": None, "at": 0.0}


def _ga_top_guide(guides):
    import time
    import urllib.request
    if time.time() - _top_guide["at"] < 6 * 3600:
        return _top_guide["slug"]
    _top_guide["at"] = time.time()
    try:
        req = urllib.request.Request(
            "http://metadata.google.internal/computeMetadata/v1/instance/service-accounts/default/token"
            "?scopes=https://www.googleapis.com/auth/analytics.readonly",
            headers={"Metadata-Flavor": "Google"})
        token = json.loads(urllib.request.urlopen(req, timeout=2).read())["access_token"]
        body = json.dumps({"dateRanges": [{"startDate": "7daysAgo", "endDate": "today"}],
                           "dimensions": [{"name": "pagePath"}], "metrics": [{"name": "screenPageViews"}],
                           "limit": 500}).encode()
        req = urllib.request.Request(
            f"https://analyticsdata.googleapis.com/v1beta/properties/{GA4_PROPERTY}:runReport", data=body,
            headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"})
        rows = json.loads(urllib.request.urlopen(req, timeout=3).read()).get("rows", [])
        views = {}
        for r in rows:
            path = r["dimensionValues"][0]["value"].split("?")[0].rstrip("/")
            slug = path.rsplit("/", 1)[-1]
            if slug in guides:  # counts both /guides/<slug> and the old flat /<slug>
                views[slug] = views.get(slug, 0) + int(r["metricValues"][0]["value"])
        _top_guide["slug"] = max(views, key=views.get) if views else None
    except Exception:
        _top_guide["slug"] = None
    return _top_guide["slug"]


def guides_lobby():
    try:
        cfg = json.loads((_LOBBY / "featured.json").read_text())
    except (OSError, ValueError):
        cfg = {}
    guides = set(cfg.get("guides", []))
    slug = cfg.get("override") or _ga_top_guide(guides) or cfg.get("default")
    page = _LOBBY / f"{slug}.html"
    return FileResponse(page if page.is_file() else STATIC / "guides" / "index.html")


@app.get("/{path:path}", include_in_schema=False)
def content_page(path: str):
    path = path.strip("/")
    if path == "guides":
        return guides_lobby()
    if ".." in path or path.startswith("_"):
        raise HTTPException(status_code=404)
    if path.endswith(".md"):
        md = _md_for(path[:-3])
        if md:
            return FileResponse(md, media_type="text/markdown; charset=utf-8")
    elif path:
        for cand in (STATIC / f"{path}.html", STATIC / path / "index.html"):
            if cand.is_file() and cand.resolve().is_relative_to(STATIC.resolve()):
                return FileResponse(cand)
    return FileResponse(STATIC / "404.html", status_code=404)
