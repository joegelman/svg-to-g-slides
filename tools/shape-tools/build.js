// Builds extension/geo-ops.js (Paper.js + paperjs-offset + src/geo.js) and
// extension/fontkit.js. Run: node build.js
const esbuild = require('esbuild');
const path = require('path');

const paperCore = require.resolve('paper/dist/paper-core.js');
const stubNode = {
  name: 'stub-paper-node',
  setup(b) {
    b.onResolve({ filter: /^paper$/ }, () => ({ path: paperCore }));
    b.onResolve({ filter: /^\.\/node\/(self|extend)\.js$/ }, (a) => ({ path: a.path, namespace: 'stub' }));
    // Paper's Node-only helpers: never needed in the browser, but make them
    // harmless if paper's agent sniffing ever thinks it is in Node.
    b.onLoad({ filter: /self\.js$/, namespace: 'stub' }, () => ({ contents: 'module.exports = typeof window !== "undefined" ? window : null;', loader: 'js' }));
    b.onLoad({ filter: /extend\.js$/, namespace: 'stub' }, () => ({ contents: 'module.exports = function () {};', loader: 'js' }));
  },
};
const aliasOnly = {
  name: 'alias-paper',
  setup(b) { b.onResolve({ filter: /^paper$/ }, () => ({ path: paperCore })); },
};

const banner = '// Generated by tools/shape-tools/build.js — do not edit. Paper.js (MIT), paperjs-offset (MIT).';
const out = process.argv[2] || path.join(__dirname, '..', '..', 'extension');

(async () => {
  await esbuild.build({
    entryPoints: [path.join(__dirname, 'src/geo.js')],
    bundle: true, format: 'iife', globalName: 'GEO', platform: 'browser', minify: true,
    plugins: [stubNode], outfile: path.join(out, 'geo-ops.js'), banner: { js: banner }, legalComments: 'none',
  });
  await esbuild.build({
    entryPoints: [path.join(__dirname, 'src/geo.js')],
    bundle: true, format: 'cjs', platform: 'node', external: ['paper'], outfile: path.join(__dirname, 'test/geo-node.cjs'),
  });
  await esbuild.build({
    entryPoints: [path.join(__dirname, 'src/fontkit-entry.js')],
    bundle: true, format: 'iife', globalName: 'FONTKIT', platform: 'browser', minify: true,
    outfile: path.join(out, 'fontkit.js'), legalComments: 'none',
    banner: { js: '// Generated by tools/shape-tools/build.js — do not edit. fontkit (MIT).' },
    define: { 'process.env.NODE_ENV': '"production"' },
  });
  console.log('built');
})().catch((e) => { console.error(e); process.exit(1); });
